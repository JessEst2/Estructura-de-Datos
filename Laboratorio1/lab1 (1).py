def informe(mm, ruta=RUTA, semilla=SEMILLA, bloque=BLOQUE):
    """
    Ejecuta todas las verificaciones y las imprime de forma legible.
    Es la función que hay que llamar para responder a "¿quedó bien la matriz?".

    `semilla` y `bloque` deben ser los mismos que se usaron en `crear_matriz`,
    porque la prueba de reproducibilidad regenera los datos imitando ese proceso.
    """
    def marca(ok):
        return "OK   " if ok else "FALLA"

    print("=" * 70)
    print("INFORME DE VERIFICACIÓN DE LA MATRIZ")
    print("=" * 70)

    d = dimensiones(mm)
    print("\n[1] DIMENSIONES")
    print(f"    Filas .................. {d['filas']:,}")
    print(f"    Columnas (bits) ........ {d['columnas_bits']:,}")
    print(f"    Bytes por fila ......... {d['bytes_por_fila']:,}")
    print(f"    Bits totales ........... {d['bits_totales']:,}")
    print(f"    Bytes totales .......... {d['bytes_totales']:,}")

    t = verificar_tamano_archivo(ruta, d["filas"])
    print(f"\n[2] TAMAÑO DEL ARCHIVO EN DISCO ....... {marca(t['ok'])}")
    print(f"    Esperado: {t['bytes_esperados']:,} bytes")
    print(f"    Real:     {t['bytes_reales']:,} bytes  ({t['gb_reales']} GB)")



    v = verificar_no_vacia(mm)
    print(f"\n[8] SIN FILAS EN BLANCO ............... {marca(v['ok'])}")
    print(f"    Filas vacías encontradas: {v['filas_vacias_encontradas']}")

    todo_ok = all([t["ok"], v["ok"]])
    print("\n" + "=" * 70)
    print("RESULTADO GLOBAL:", "TODO CORRECTO" if todo_ok else "HAY FALLAS")
    print("=" * 70)
    return todo_ok


def muestra(mm):
    """
    Muestra ejemplos concretos de lectura: casillas sueltas, principio de la
    primera fila, principio de la primera columna, una esquina, etc.
    """
    n_filas, n_cols = mm.shape[0], mm.shape[1] * 8

    print("=" * 70)
    print("MUESTRAS DE CONTENIDO")
    print("=" * 70)

    print("\n-- Primeros 20 elementos de la PRIMERA FILA --")
    print("   ", leer_segmento_fila(mm, 0, 0, 20))

    print("\n-- Primeros 10 elementos de la PRIMERA COLUMNA --")
    print("   ", leer_columna(mm, 0, 0, 10))

    print(f"\n-- Fila 0 completa (resumen, son {n_cols:,} bits) --")
    fila0 = leer_fila(mm, 0)
    print(f"    longitud = {len(fila0):,} bits")


    print("\n-- Esquina superior izquierda 8x8 --")
    for fila in leer_submatriz(mm, 0, 8, 0, 8):
        print("    ", " ".join(str(b) for b in fila))


    print("\n-- Columna 0 completa (puede tardar: recorre todo el archivo) --")
    col0 = leer_columna(mm, 0)
    print(f"    longitud = {len(col0):,} bits")


