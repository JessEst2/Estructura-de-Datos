def leer_fila(mm, fila):
    """
    Devuelve la FILA COMPLETA como un array de n bits (0 y 1).

    Usa np.unpackbits, que convierte cada byte en sus 8 bits. Una fila de
    12.500 bytes se convierte en 100.000 valores 0/1 -> 100 KB en RAM,
    perfectamente manejable.
    """
    return np.unpackbits(np.asarray(mm[fila]))


def leer_segmento_fila(mm, fila, inicio, fin):
    """
    Devuelve los bits de la fila entre las columnas [inicio, fin) sin
    desempaquetar la fila entera (más eficiente para trozos pequeños).

    como los bits vienen agrupados de 8 en 8, hay que leer los bytes
    que "cubren" el rango pedido y luego recortar los sobrantes de los extremos.
    """
    byte_ini = inicio // 8              # primer byte que toca el rango
    byte_fin = (fin + 7) // 8           # primer byte que YA no toca el rango
    bits = np.unpackbits(np.asarray(mm[fila, byte_ini:byte_fin]))
    desfase = inicio - byte_ini * 8     # cuántos bits sobran al principio
    return bits[desfase:desfase + (fin - inicio)]


def leer_columna(mm, columna, inicio=0, fin=None):
    """
    Devuelve una COLUMNA COMPLETA (o un tramo) como array de bits.

    Ojo con el rendimiento: una columna toca UNA celda de cada fila, y las filas
    están separadas 12.500 bytes en disco. Leer una columna completa obliga al
    sistema a recorrer todo el archivo (1,25 GB), así que es mucho más lento que
    leer una fila. Por eso existe el parámetro `fin` (ver `primeros_de_columna`).

    La operación está vectorizada: `mm[inicio:fin, byte_col]` extrae de golpe el
    byte correspondiente de cada fila, y luego se desplaza y enmascara todo junto.
    """
    if fin is None:
        fin = mm.shape[0]
    byte_col = columna // 8
    posicion = 7 - (columna % 8)
    columna_bytes = np.asarray(mm[inicio:fin, byte_col])
    return ((columna_bytes >> posicion) & 1).astype(np.uint8)


def leer_submatriz(mm, fila_ini, fila_fin, col_ini, col_fin):
    """
    Devuelve un bloque rectangular de bits como matriz 2D.
    Útil para "mirar con lupa" una esquina de la matriz (p. ej. 5x5).
    """
    return np.array([
        leer_segmento_fila(mm, f, col_ini, col_fin)
        for f in range(fila_ini, fila_fin)
    ])


