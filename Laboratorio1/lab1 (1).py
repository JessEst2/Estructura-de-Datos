def dimensiones(mm):
    """
    Devuelve un diccionario con las dimensiones REALES de la matriz, deducidas
    del propio objeto memmap (no de las constantes del programa).

    - filas: mm.shape[0]
    - bytes_por_fila: mm.shape[1]  (lo que hay físicamente en disco)
    - columnas_bits: bytes_por_fila * 8 (las columnas lógicas de la matriz)
    """
    filas, bytes_fila = mm.shape
    return {
        "filas": filas,
        "bytes_por_fila": bytes_fila,
        "columnas_bits": bytes_fila * 8,
        "bits_totales": filas * bytes_fila * 8,
        "bytes_totales": filas * bytes_fila,
    }


def verificar_tamano_archivo(ruta=RUTA, n=N):
    """
    Comprueba que el archivo en disco pesa EXACTAMENTE lo que debería.

    Si el tamaño no coincide, el archivo está incompleto o corrupto y todas las
    lecturas estarían desplazadas (leeríamos basura).
    """
    esperado = n * (n // 8)
    real = os.path.getsize(ruta)
    return {
        "ok": esperado == real,
        "bytes_esperados": esperado,
        "bytes_reales": real,
        "gb_reales": round(real / 1024**3, 3),
    }




def verificar_no_vacia(mm, cuantas=20, semilla=4):
    """
    Comprueba que no hay filas completamente a cero (síntoma típico de un bloque
    que nunca se escribió o de un flush que no llegó a disco).
    """
    rng = np.random.default_rng(semilla)
    filas = rng.integers(0, mm.shape[0], size=cuantas)
    vacias = [int(f) for f in filas if not np.asarray(mm[int(f)]).any()]
    return {"ok": len(vacias) == 0, "filas_vacias_encontradas": vacias}


