# -*- coding: utf-8 -*-
"""
===============================================================================
 MATRIZ BINARIA DE 100.000 x 100.000 BITS ALMACENADA EN DISCO (memmap)
===============================================================================

QUÉ ES np.memmap
----------------
`np.memmap` crea un array de numpy que NO vive en la RAM, sino que está
"mapeado" a un archivo del disco duro. Cuando pedimos `mm[500, 154]`, el
sistema operativo trae del disco solo la porción necesaria (una página de
memoria, típicamente 4 KB). Así podemos manejar 1,25 GB (o mucho más) con
poquísima RAM.

Modos que usamos:
    "w+" -> crear/sobrescribir el archivo y poder leer y escribir.
    "r"  -> abrir solo lectura (protege el archivo de modificaciones).

POR QUÉ SE ESCRIBE POR BLOQUES DE 2000 FILAS
--------------------------------------------
Generar los 1,25 GB de números aleatorios de un solo golpe exigiría 1,25 GB de
RAM. Generando 2000 filas a la vez, cada bloque ocupa solo
2000 x 12.500 = 25 MB, se vuelca a disco con `.flush()` y se libera.

===============================================================================
"""

import os
import numpy as np

# -----------------------------------------------------------------------------
# PARÁMETROS GLOBALES
# -----------------------------------------------------------------------------

N = 100_000            # Número de filas y de columnas LÓGICAS (bits) de la matriz
BYTES_FILA = N // 8    # Bytes que ocupa cada fila en disco (12.500)
RUTA = "matriz.bin"    # Nombre del archivo binario
SEMILLA = 42           # Semilla del generador aleatorio (hace todo reproducible)
BLOQUE = 2000          # Cuántas filas se generan y escriben de una sola vez

# Tabla de "popcount": para cada valor posible de un byte (0..255) guarda cuántos
# bits en 1 tiene. Sirve para contar unos MUY rápido sin desempaquetar bit a bit.
# np.unpackbits convierte cada byte en sus 8 bits; luego sumamos por fila.
TABLA_POPCOUNT = np.unpackbits(
    np.arange(256, dtype=np.uint8).reshape(-1, 1), axis=1
).sum(axis=1).astype(np.uint8)


# =============================================================================
# 1. CREACIÓN DE LA MATRIZ
# =============================================================================

def crear_matriz(ruta=RUTA, n=N, semilla=SEMILLA, bloque=BLOQUE, verbose=True):
    """
    Crea en disco el archivo binario con la matriz de n x n bits.

    Parámetros
    ----------
    ruta : str
        Nombre del archivo que se va a crear (se sobrescribe si ya existe).
    n : int
        Número de filas y columnas lógicas (bits). Debe ser múltiplo de 8.
    semilla : int
        Semilla del generador aleatorio. Con la misma semilla, el archivo
        generado es SIEMPRE idéntico (esto lo aprovecha la verificación).
    bloque : int
        Cuántas filas se escriben por iteración (controla el uso de RAM).
    verbose : bool
        Si True, imprime el progreso.

    Retorna
    -------
    str : la ruta del archivo creado.
    """
    # Si n no es múltiplo de 8 no podríamos empaquetar filas completas en bytes.
    if n % 8 != 0:
        raise ValueError(f"n debe ser múltiplo de 8 para empaquetar bits (n={n})")

    bytes_fila = n // 8

    # mode="w+" -> crea el archivo del tamaño exacto (n * bytes_fila) y permite escribir.
    mm = np.memmap(ruta, dtype=np.uint8, mode="w+", shape=(n, bytes_fila))

    # Generador aleatorio moderno de numpy. Con semilla fija = resultados reproducibles.
    rng = np.random.default_rng(semilla)

    for i in range(0, n, bloque):
        # Cuántas filas escribimos en esta vuelta (la última puede ser más corta).
        filas = min(bloque, n - i)

        # rng.integers(0, 256, ...) genera bytes aleatorios: cada byte son 8 bits
        # aleatorios de la matriz. Es 8 veces más rápido que generar bit a bit.
        mm[i:i + filas] = rng.integers(0, 256, size=(filas, bytes_fila), dtype=np.uint8)

        # flush() obliga al sistema operativo a volcar a disco lo escrito.
        mm.flush()

        if verbose and (i // bloque) % 10 == 0:
            print(f"  escritas {i + filas:,} / {n:,} filas", end="\r")

    # del mm cierra el mapeo y libera el archivo.
    del mm

    if verbose:
        print(f"\nArchivo '{ruta}' creado: {os.path.getsize(ruta):,} bytes")
    return ruta


def abrir_matriz(ruta=RUTA, n=N):
    """
    Abre el archivo ya creado en modo SOLO LECTURA.

    Devuelve un objeto memmap con forma (n, n // 8): n filas y n//8 columnas
    de BYTES (no de bits). Ojo: mm.shape[1] son bytes, no columnas lógicas.
    """
    return np.memmap(ruta, dtype=np.uint8, mode="r", shape=(n, n // 8))


